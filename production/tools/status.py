#!/usr/bin/env python3
"""
Production dashboard for The Human Story.

Single source of truth: production/tools/status.json (edit ONLY through this tool).
Every change re-renders production/reports/dashboard.md and production/reports/approvals.md.

Usage
  status.py show [--episode EP]
  status.py new-episode --episode EP --title "Title" [--duration 600]
  status.py add  --episode EP --id TASK --agent AGENT --task "desc" [--depends a,b] [--next "..."]
  status.py set  --episode EP --id TASK [--status S] [--next "..."] [--deliverable PATH]... [--issue "..."]... [--resolve N]... [--note "..."]
  status.py approval CHECKPOINT --episode EP --state PENDING|APPROVED|CHANGES_REQUESTED [--note "..."]
  status.py active EP
  status.py rename-episode --episode EP --to NEWEP [--title "..."] [--duration S]
  status.py render
Statuses: NOT STARTED, IN PROGRESS, BLOCKED, AWAITING REVIEW, COMPLETED
Checkpoints: script, style, storyboard, final-render
"""
import argparse, datetime as dt, fcntl, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DB = os.path.join(ROOT, "production/tools/status.json")
DASH = os.path.join(ROOT, "production/reports/dashboard.md")
APPR = os.path.join(ROOT, "production/reports/approvals.md")
STATUSES = ["NOT STARTED", "IN PROGRESS", "BLOCKED", "AWAITING REVIEW", "COMPLETED"]
AGENTS = ["director", "researcher", "scriptwriter", "storyboard", "animator", "environment-designer",
          "audio-engineer", "video-editor", "quality-control", "youtube-specialist", "user"]
CHECKPOINTS = {"script": "Final episode script", "style": "Initial character & animation style",
               "storyboard": "Final storyboard before full production", "final-render": "Final render before publishing"}
PIPELINE = [
    ("brief", "director", "Write episode brief and task plan", []),
    ("research", "researcher", "Research subject; research notes + sources", ["brief"]),
    ("keywords", "youtube-specialist", "Keyword and title research", ["brief"]),
    ("script", "scriptwriter", "Write narration script fitted to duration", ["research"]),
    ("script-factcheck", "researcher", "Fact-check the script", ["script"]),
    ("script-qc", "quality-control", "QC review of the script", ["script-factcheck"]),
    ("style-sample", "animator", "Character/animation style sample for approval", ["brief"]),
    ("narration", "audio-engineer", "Generate narration, timings and SRT", ["approval:script"]),
    ("storyboard", "storyboard", "Timestamped storyboard + asset requests", ["approval:script"]),
    ("characters", "animator", "Build characters and character animation", ["approval:style", "approval:storyboard"]),
    ("environments", "environment-designer", "Build environments, maps, vehicles, effects", ["approval:storyboard"]),
    ("music-sfx", "audio-engineer", "Music, SFX and mix", ["storyboard"]),
    ("assembly", "video-editor", "Assemble timeline and preview renders", ["narration", "characters", "environments", "music-sfx"]),
    ("final-render", "video-editor", "Render and verify final MP4", ["assembly"]),
    ("final-qc", "quality-control", "QC review of final render", ["final-render"]),
    ("publishing-pack", "youtube-specialist", "Title, description, chapters, tags, thumbnail brief, checklist", ["final-qc"]),
    ("wrap", "director", "Final report to the user (user publishes manually)", ["approval:final-render"]),
]


def now():
    return dt.datetime.now().strftime("%Y-%m-%d %H:%M")


def load():
    if not os.path.exists(DB):
        return {"active": None, "episodes": {}}
    with open(DB) as f:
        return json.load(f)


def save(db):
    tmp = DB + ".tmp"
    with open(tmp, "w") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)
    os.replace(tmp, DB)
    render(db)


def ep_or_die(db, ep):
    ep = ep or db.get("active")
    if not ep or ep not in db["episodes"]:
        sys.exit(f"Unknown episode '{ep}'. Known: {', '.join(db['episodes']) or 'none'}")
    return ep, db["episodes"][ep]


def task_or_die(e, tid):
    for t in e["tasks"]:
        if t["id"] == tid:
            return t
    sys.exit(f"Unknown task '{tid}'. Known: {', '.join(t['id'] for t in e['tasks'])}")


def dep_state(e, d):
    if d.startswith("approval:"):
        return e["approvals"].get(d.split(":", 1)[1], {}).get("state", "NOT REQUESTED")
    for t in e["tasks"]:
        if t["id"] == d:
            return t["status"]
    return "?"


def render(db):
    lines = ["# Production dashboard — The Human Story", "",
             "_Generated by `production/tools/status.py` — do not edit by hand._", "",
             f"Last updated: {now()}  ·  Active episode: **{db.get('active') or '—'}**", ""]
    for ep, e in db["episodes"].items():
        counts = {s: sum(1 for t in e["tasks"] if t["status"] == s) for s in STATUSES}
        lines += [f"## {ep} — {e['title']}", "",
                  "Progress: " + " · ".join(f"{s}: {n}" for s, n in counts.items() if n), ""]
        if e.get("notes"):
            lines += [f"> {e['notes']}", ""]
        lines += ["| Task | Agent | Assigned task | Status | Dependencies | Completed deliverables | Outstanding issues | Next action |",
                  "|---|---|---|---|---|---|---|---|"]
        for t in e["tasks"]:
            deps = ", ".join(f"{d} ({dep_state(e, d)})" for d in t["depends"]) or "—"
            dels = "<br>".join(f"`{p}`" for p in t["deliverables"]) or "—"
            iss = "<br>".join(f"#{i + 1} {x['text']}" for i, x in enumerate(t["issues"]) if not x.get("resolved")) or "—"
            lines.append(f"| `{t['id']}` | {t['agent']} | {t['task']} | **{t['status']}** | {deps} | {dels} | {iss} | {t.get('next') or '—'} |")
        lines += ["", "Approvals: " + " · ".join(f"{CHECKPOINTS[k]}: **{v['state']}**" for k, v in e["approvals"].items()), ""]
    os.makedirs(os.path.dirname(DASH), exist_ok=True)
    with open(DASH, "w") as f:
        f.write("\n".join(lines) + "\n")
    al = ["# Approvals — The Human Story", "", "_The user's sign-off is required at each checkpoint. Generated by `status.py`._", ""]
    for ep, e in db["episodes"].items():
        al += [f"## {ep} — {e['title']}", "", "| Checkpoint | State | Updated | Note |", "|---|---|---|---|"]
        for k, v in e["approvals"].items():
            al.append(f"| {CHECKPOINTS[k]} | **{v['state']}** | {v.get('updated', '—')} | {v.get('note', '')} |")
        al.append("")
    with open(APPR, "w") as f:
        f.write("\n".join(al) + "\n")


def show(db, ep=None):
    eps = [ep] if ep else list(db["episodes"])
    for e_id in eps:
        e_id, e = ep_or_die(db, e_id)
        print(f"\n== {e_id} — {e['title']} ==")
        for t in e["tasks"]:
            open_issues = [x["text"] for x in t["issues"] if not x.get("resolved")]
            blocked_by = [d for d in t["depends"] if dep_state(e, d) not in ("COMPLETED", "APPROVED")]
            print(f"  [{t['status']:<15}] {t['id']:<17} {t['agent']:<20} {t['task']}")
            if blocked_by and t["status"] == "NOT STARTED":
                print(f"      waiting on: {', '.join(blocked_by)}")
            if t["deliverables"]:
                print(f"      deliverables: {', '.join(t['deliverables'])}")
            for i in open_issues:
                print(f"      issue: {i}")
            if t.get("next"):
                print(f"      next: {t['next']}")
        print("  approvals: " + ", ".join(f"{k}={v['state']}" for k, v in e["approvals"].items()))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("show"); s.add_argument("--episode")
    s = sub.add_parser("new-episode"); s.add_argument("--episode", required=True); s.add_argument("--title", required=True); s.add_argument("--duration", type=int, default=600)
    s = sub.add_parser("add"); s.add_argument("--episode"); s.add_argument("--id", required=True); s.add_argument("--agent", required=True, choices=AGENTS); s.add_argument("--task", required=True); s.add_argument("--depends", default=""); s.add_argument("--next")
    s = sub.add_parser("set"); s.add_argument("--episode"); s.add_argument("--id", required=True); s.add_argument("--status", choices=STATUSES); s.add_argument("--next"); s.add_argument("--deliverable", action="append", default=[]); s.add_argument("--issue", action="append", default=[]); s.add_argument("--resolve", action="append", type=int, default=[]); s.add_argument("--agent", choices=AGENTS); s.add_argument("--task"); s.add_argument("--force", action="store_true")
    s = sub.add_parser("approval"); s.add_argument("checkpoint", choices=list(CHECKPOINTS)); s.add_argument("--episode"); s.add_argument("--state", required=True, choices=["NOT REQUESTED", "PENDING", "APPROVED", "CHANGES_REQUESTED"]); s.add_argument("--note", default="")
    s = sub.add_parser("active"); s.add_argument("episode")
    s = sub.add_parser("rename-episode"); s.add_argument("--episode", required=True); s.add_argument("--to", required=True); s.add_argument("--title"); s.add_argument("--duration", type=int)
    sub.add_parser("render")
    a = ap.parse_args()

    os.makedirs(os.path.dirname(DB), exist_ok=True)
    with open(DB + ".lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        db = load()
        if a.cmd == "show":
            show(db, a.episode); return
        if a.cmd == "render":
            render(db); print("rendered"); return
        if a.cmd == "active":
            ep_or_die(db, a.episode); db["active"] = a.episode
        elif a.cmd == "rename-episode":
            ep, e = ep_or_die(db, a.episode)
            if a.to != ep:
                if a.to in db["episodes"]:
                    sys.exit(f"Episode {a.to} already exists")
                db["episodes"] = {(a.to if k == ep else k): v for k, v in db["episodes"].items()}
                if db.get("active") == ep: db["active"] = a.to
            e = db["episodes"][a.to]
            if a.title: e["title"] = a.title
            if a.duration: e["duration"] = a.duration
        elif a.cmd == "new-episode":
            if a.episode in db["episodes"]:
                sys.exit(f"Episode {a.episode} already exists")
            db["episodes"][a.episode] = {
                "title": a.title, "duration": a.duration, "created": now(), "notes": "",
                "approvals": {k: {"state": "NOT REQUESTED"} for k in CHECKPOINTS},
                "tasks": [{"id": i, "agent": ag, "task": d, "status": "NOT STARTED", "depends": dep,
                           "deliverables": [], "issues": [], "next": "", "updated": now()} for i, ag, d, dep in PIPELINE],
            }
            db["active"] = a.episode
        elif a.cmd == "add":
            ep, e = ep_or_die(db, a.episode)
            if any(t["id"] == a.id for t in e["tasks"]):
                sys.exit(f"Task {a.id} exists")
            e["tasks"].append({"id": a.id, "agent": a.agent, "task": a.task, "status": "NOT STARTED",
                               "depends": [d for d in a.depends.split(",") if d], "deliverables": [], "issues": [],
                               "next": a.next or "", "updated": now()})
        elif a.cmd == "set":
            ep, e = ep_or_die(db, a.episode)
            t = task_or_die(e, a.id)
            for p in a.deliverable:
                if not os.path.exists(os.path.join(ROOT, p)):
                    sys.exit(f"Deliverable not found on disk: {p}")
                if p not in t["deliverables"]:
                    t["deliverables"].append(p)
            for i in a.issue:
                t["issues"].append({"text": i, "opened": now()})
            for n in a.resolve:
                t["issues"][n - 1]["resolved"] = now()
            if a.agent: t["agent"] = a.agent
            if a.task: t["task"] = a.task
            if a.next is not None: t["next"] = a.next
            if a.status:
                if a.status == "COMPLETED" and not t["deliverables"] and not a.force:
                    sys.exit("Refusing COMPLETED with no deliverables on disk (use --deliverable, or --force for coordination tasks).")
                if a.status == "COMPLETED" and any(not x.get("resolved") for x in t["issues"]) and not a.force:
                    sys.exit("Refusing COMPLETED with open issues (resolve them or use --force).")
                t["status"] = a.status
            t["updated"] = now()
        elif a.cmd == "approval":
            ep, e = ep_or_die(db, a.episode)
            e["approvals"][a.checkpoint] = {"state": a.state, "updated": now(), "note": a.note}
        save(db)
        print("ok — dashboard updated: production/reports/dashboard.md")


if __name__ == "__main__":
    main()
